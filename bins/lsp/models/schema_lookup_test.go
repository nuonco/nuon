func TestDetectSchemaType(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected string
	}{
		{
			name:     "schema directive with type path",
			input:    "#:schema https://api.nuon.co/v1/general/config-schema/helm\n\n[public_repo]\n",
			expected: "helm",
		},
		{
			name:     "schema directive with trailing slash",
			input:    "#:schema https://api.nuon.co/v1/general/config-schema/sandbox/\n",
			expected: "sandbox",
		},
		{
			name:     "schema directive with deprecated type query",
			input:    "#:schema https://api.nuon.co/v1/general/config-schema?type=runner\n",
			expected: "runner",
		},
		{
			name:     "schema directive with deprecated source query",
			input:    "#:schema https://api.nuon.co/v1/general/config-schema?source=inputs\n",
			expected: "inputs",
		},
		{
			name:     "schema directive after prose comment",
			input:    "# this branch is updated when a git tag is pushed\n#:schema https://api.nuon.co/v1/general/config-schema/terraform\n",
			expected: "terraform",
		},
		{
			name:     "schema directive with unknown type is surfaced",
			input:    "#:schema https://api.nuon.co/v1/general/config-schema/branch\n",
			expected: "branch",
		},
		{
			name:     "schema directive wins over bare type",
			input:    "# helm\n#:schema https://api.nuon.co/v1/general/config-schema/terraform\n",
			expected: "terraform",
		},
		{
			name:     "bare comment with valid schema type",
			input:    "#helm\n",
			expected: "helm",
		},
		{
			name:     "bare comment with schema type and whitespace",
			input:    "  #helm  \n",
			expected: "helm",
		},
		{
			name:     "bare comment with underscore alias",
			input:    "# docker_build\n",
			expected: "docker_build",
		},
		{
			name:     "multiple bare types, uses first",
			input:    "#helm\n#terraform\n",
			expected: "helm",
		},
		{
			name:     "prose comment is ignored",
			input:    "# this branch is updated when a git tag is pushed with the provided prefix\nname = \"tag-release\"\n",
			expected: "",
		},
		{
			name:     "prose comment before bare type",
			input:    "# generated by nuon\n# helm\n",
			expected: "helm",
		},
		{
			name:     "directive after TOML content is ignored",
			input:    "[public_repo]\n#:schema https://api.nuon.co/v1/general/config-schema/helm\n",
			expected: "",
		},
		{
			name:     "empty lines before comment",
			input:    "\n\n#terraform\n",
			expected: "terraform",
		},
		{
			name:     "no comment returns empty string",
			input:    "[public_repo]\nusername = \"test\"\n",
			expected: "",
		},
		{
			name:     "empty comment returns empty string",
			input:    "#\n[public_repo]\n",
			expected: "",
		},
		{
			name:     "empty directive returns empty string",
			input:    "#:schema\n[public_repo]\n",
			expected: "",
		},
		{
			name:     "only empty lines returns empty string",
			input:    "\n\n\n",
			expected: "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := DetectSchemaType(tt.input)
			if result != tt.expected {
				t.Errorf("DetectSchemaType() = %q, want %q", result, tt.expected)
			}
		})
	}
}

func TestDetectSchemaPosition(t *testing.T) {
	tests := []struct {
		name  string
		input string
		line  int
		start int
		end   int
	}{
		{
			name:  "directive ref span",
			input: "# comment\n#:schema https://api.nuon.co/v1/general/config-schema/branch\n",
			line:  1,
			start: 9,
			end:   9 + len("https://api.nuon.co/v1/general/config-schema/branch"),
		},
		{
			name:  "bare type span",
			input: "\n  # helm\n",
			line:  1,
			start: 4,
			end:   8,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			decl := DetectSchema(tt.input)
			if decl == nil {
				t.Fatal("DetectSchema() = nil")
			}
			if decl.Line != tt.line || decl.Start != tt.start || decl.End != tt.end {
				t.Errorf("DetectSchema() position = (%d,%d,%d), want (%d,%d,%d)",
					decl.Line, decl.Start, decl.End, tt.line, tt.start, tt.end)
			}
		})
	}
}
